package io.dewey.openapi.client.go

import io.dewey.openapi.client.common.splitWords
import io.dewey.openapi.wire.Body
import io.dewey.openapi.wire.Declaration
import io.dewey.openapi.wire.EnumDeclaration
import io.dewey.openapi.wire.ObjectDeclaration
import io.dewey.openapi.wire.ScalarKind
import io.dewey.openapi.wire.WireType

internal const val GENERATED_HEADER = "// Code generated by the dewey client generator. DO NOT EDIT.\n\n"

private val GO_KEYWORDS =
    setOf(
        "break",
        "case",
        "chan",
        "const",
        "continue",
        "default",
        "defer",
        "else",
        "fallthrough",
        "for",
        "func",
        "go",
        "goto",
        "if",
        "import",
        "interface",
        "map",
        "package",
        "range",
        "return",
        "select",
        "struct",
        "switch",
        "type",
        "var",
    )

/** An exported Go identifier for a name the server uses. Go spells the trailing Id of an identifier ID. */
internal fun exported(name: String): String {
    val words = name.split(Regex("[^A-Za-z0-9]+")).filter { it.isNotEmpty() }
    val joined =
        words.joinToString("") { word ->
            // A SCREAMING_CASE word (an enum value) reads as one capitalized word, a camelCase one keeps its humps
            val normalized = if (word.all { !it.isLowerCase() }) word.lowercase() else word
            normalized.replaceFirstChar(Char::uppercaseChar)
        }
    return if (joined.endsWith("Id")) joined.dropLast(2) + "ID" else joined
}

/** A parameter name in a generated signature, which a Go keyword or a name the function uses itself cannot be. */
internal fun parameterName(name: String): String {
    val camel = exported(name).replaceFirstChar(Char::lowercaseChar).let { if (it == "iD") "id" else it }
    return if (camel in GO_KEYWORDS || camel in RESERVED_PARAMETERS) "${camel}Param" else camel
}

private val RESERVED_PARAMETERS = setOf("ctx", "body", "opts", "c", "query", "out", "err", "request")

/** The models live in a package of their own, which [models] names wherever they are referred to from outside it. */
internal fun WireType.go(models: String = ""): String {
    val base = goBase(models)
    // A slice and a map already say nothing with nil, a pointer to them would only add a second way to say it
    return if (nullable && this !is WireType.ListOf && this !is WireType.MapOf) "*$base" else base
}

private fun WireType.goBase(models: String): String =
    when (this) {
        is WireType.Scalar -> {
            when (kind) {
                ScalarKind.STRING, ScalarKind.CHAR -> "string"
                ScalarKind.UUID -> "${models}UUID"
                ScalarKind.DATE -> "${models}Date"
                ScalarKind.DATE_TIME -> "time.Time"
                ScalarKind.BOOLEAN -> "bool"
                ScalarKind.BYTE -> "int8"
                ScalarKind.SHORT -> "int16"
                ScalarKind.INT -> "int32"
                ScalarKind.LONG -> "int64"
                ScalarKind.FLOAT -> "float32"
                ScalarKind.DOUBLE -> "float64"
            }
        }

        is WireType.ListOf -> {
            "[]${element.go(models)}"
        }

        // A map key cannot be absent, so it is the type itself even when the server marks it nullable
        is WireType.MapOf -> {
            "map[${key.goBase(models)}]${value.go(models)}"
        }

        is WireType.Named -> {
            models + exported(name) + typeArguments(arguments.map { it.go(models) })
        }

        is WireType.TypeParameter -> {
            name
        }
    }

internal fun WireType.usesTime(): Boolean =
    when (this) {
        is WireType.Scalar -> kind == ScalarKind.DATE_TIME
        is WireType.ListOf -> element.usesTime()
        is WireType.MapOf -> key.usesTime() || value.usesTime()
        is WireType.Named -> arguments.any { it.usesTime() }
        is WireType.TypeParameter -> false
    }

internal fun Body.usesTime(): Boolean = this is Body.Json && type.usesTime()

private fun typeArguments(arguments: List<String>): String =
    if (arguments.isEmpty()) "" else arguments.joinToString(", ", "[", "]")

internal fun Declaration.usesTime(): Boolean =
    when (this) {
        is EnumDeclaration -> false
        is ObjectDeclaration -> properties.any { it.type.usesTime() }
    }

/** The file of one model in the models package. */
internal fun Declaration.goFile(packageName: String): String =
    buildString {
        append(GENERATED_HEADER)
        append("package $packageName\n\n")
        if (usesTime()) append("import \"time\"\n\n")
        append(
            when (this@goFile) {
                is EnumDeclaration -> enumType()
                is ObjectDeclaration -> structType()
            },
        )
    }

/** A Go file name for a model, lower snake case as Go spells them. */
internal fun fileName(name: String): String = splitWords(exported(name), "_") + ".go"

private fun EnumDeclaration.enumType(): String {
    val type = exported(name)
    return buildString {
        append("type $type string\n\n")
        append("const (\n")
        values.forEach { append("\t$type${exported(it)} $type = \"$it\"\n") }
        append(")\n")
    }
}

// An optional property is a Patch, whose omitzero tag leaves it out of the JSON while it is unset
private fun ObjectDeclaration.structType(): String =
    buildString {
        description?.let { append(comment(it)) }
        val parameters = if (typeParameters.isEmpty()) {
            ""
        } else {
            typeParameters.joinToString(
                ", ",
                "[",
                " any]",
            ) { it.name }
        }
        if (properties.isEmpty()) {
            append("type ${exported(name)}$parameters struct{}\n")
            return@buildString
        }
        append("type ${exported(name)}$parameters struct {\n")
        properties.sortedBy { it.name }.forEach { property ->
            property.description?.let { append(comment(it, "\t")) }
            if (property.optional) {
                append(
                    "\t${exported(property.name)} Patch[${property.type.go()}] `json:\"${property.name},omitzero\"`\n",
                )
            } else {
                append("\t${exported(property.name)} ${property.type.go()} `json:\"${property.name}\"`\n")
            }
        }
        append("}\n")
    }

internal fun comment(
    text: String,
    indent: String = "",
): String = text.lines().joinToString("") { "$indent// ${it.trimEnd()}".trimEnd() + "\n" }
